"""Поток событий для интерфейса: `GET /api/v1/events`, формат SSE.

Экраны опрашивали ручки по таймеру: десяток вкладок превращались в постоянный поток
запросов, а новость всё равно приезжала с задержкой в целый период опроса. Здесь один
открытый ответ на вкладку, и в него пишется только то, что действительно изменилось.
Откуда берутся сами изменения и почему их не публикуют из мест правки — в докстроке
`app/services/events.py`.

**Ручка не держит сессию базы, и это самое неочевидное место всего файла.** Зависимость
`GetDB` (`app/api/deps.py`) — yield-зависимость: FastAPI закрывает её не после того,
как отработала функция, а после того, как отдано тело ответа. Тело здесь живёт
минутами и часами, то есть соединение из пула было бы занято ровно столько же. Пул по
умолчанию `pool_size=5, max_overflow=10` (`app/db/session.py` создаёт движок без
переопределений), так что полтора десятка открытых вкладок оставили бы весь остальной
API без соединений — и выглядело бы это не как «сломался поток», а как «сайт целиком
завис». Поэтому проверка пользователя делается своей короткой сессией, которая
закрывается до того, как начнётся стрим.

**Права проверяются один раз, на открытии потока.** Это ограничение, а не оплошность:
перепроверять их каждый такт означало бы ходить в базу за пользователем по числу
подписчиков. Ограничено оно по времени сроком жизни сессии — `SESSION_MAX_AGE`, то
есть двенадцатью часами (`app/core/config.py`): дальше cookie перестаёт приниматься, и
переоткрытый поток проверит права заново. Понижение в правах внутри этих двенадцати
часов доедет до уже открытого потока только после его переоткрытия; на ручках, которые
что-то меняют, всё честно — там проверка на каждом запросе.

Аутентификация — та же сессионная cookie, что у всех ручек, и другого варианта нет:
`EventSource` в браузере не умеет слать произвольные заголовки, так что ни `Bearer`, ни
свой ключ сюда не передать. Cookie в этом смысле не компромисс, а единственный рабочий
способ — и она уже есть.
"""
from __future__ import annotations

import asyncio
import json
import logging

from fastapi import APIRouter, Request
from fastapi.responses import StreamingResponse

from app.api.deps import current_user
from app.core.access import sections_for
from app.core.config import get_settings
from app.db.session import get_session_maker
from app.services import events

logger = logging.getLogger("radar")

router = APIRouter(prefix="/api/v1", tags=["events"])

# `Content-Length` не ставим — его тут и не может быть: длина ответа неизвестна и
# бесконечна, а `StreamingResponse` его не проставляет.
#
# `X-Accel-Buffering: no` — тот самый заголовок, ради которого этот словарь и заведён.
# Промежуточный прокси по умолчанию копит ответ в буфере и отдаёт клиенту кусками
# покрупнее; для страницы это ускорение, для потока — смерть: события лежат в буфере
# прокси, пока не наберётся килобайт, и «реальное время» превращается в случайную
# задержку. Заголовок отключает буферизацию у nginx и понимается Caddy, за которым мы
# и стоим.
#
# Hop-by-hop заголовки вроде `Connection: keep-alive` здесь намеренно не выставляются:
# ими распоряжается сервер, а в HTTP/2 они прямо запрещены.
STREAM_HEADERS = {
    "Cache-Control": "no-store",
    "X-Accel-Buffering": "no",
}


def _frame(name: str, data: dict) -> str:
    """Один кадр SSE. Формат простой настолько, что отдельная библиотека была бы
    зависимостью ради двух склеек строк.

    `ensure_ascii=False` — тексты у нас русские, а поток и так объявлен в UTF-8;
    экранирование раздуло бы кадр втрое без единого выигрыша.
    """
    return f"event: {name}\ndata: {json.dumps(data, ensure_ascii=False)}\n\n"


@router.get("/events")
async def event_stream(request: Request):
    """Открыть поток изменений.

    Порядок кадров: сначала `hello` с периодом опроса и разделами, доступными этому
    пользователю, следом — полный снимок состояния, дальше только изменившееся.
    Снимок сразу, а не по первому изменению: иначе только что открытый экран слеп до
    тех пор, пока в системе что-нибудь не произойдёт.

    Молчащий поток раз в `EVENTS_HEARTBEAT` секунд получает комментарий `: ping` —
    строку, начинающуюся с двоеточия. Это часть формата SSE, клиент её игнорирует, а
    прокси и операционная система видят живой трафик и не рвут соединение как
    зависшее.

    `Last-Event-ID` не поддерживается, и поля `id:` в кадрах нет намеренно:
    переподключившемуся нечего доигрывать — он получает `hello` и полный снимок, то
    есть сразу текущую правду, а не пропущенную историю.
    """
    # Своя короткая сессия вместо `GetDB` — см. докстроку модуля. Логика проверки не
    # переписана, а позвана та же самая: разъехавшись, две копии дали бы поток,
    # который пускает туда, куда обычные ручки уже не пускают.
    async with get_session_maker()() as db:
        user = await current_user(request, db)
        role, email = str(user.role), user.email

    settings = get_settings()

    async def frames():
        sub = events.subscribe(role)
        try:
            yield _frame("hello", {
                "interval": settings.EVENTS_POLL_INTERVAL,
                "sections": sections_for(role),
                # Какие события этому подписчику вообще будут приходить. Клиенту это
                # нужнее, чем список разделов: иначе он не отличит «прогонов сейчас
                # нет» от «прогоны мне не положены» и будет вечно ждать кадра, который
                # не придёт.
                "events": [n for n in events.EVENT_ORDER if sub.wants(n)],
            })
            while True:
                try:
                    name, data = await asyncio.wait_for(
                        sub.queue.get(), timeout=settings.EVENTS_HEARTBEAT)
                except TimeoutError:
                    yield ": ping\n\n"
                    continue
                yield _frame(name, data)
        finally:
            # Сюда попадаем и по нормальному закрытию, и по отмене корутины — а
            # закрытая вкладка, обрыв сети и уход со страницы приходят именно отменой.
            # `unsubscribe` поэтому синхронный: в отменённой задаче ожидание сразу
            # получило бы `CancelledError`, и уборка не доделалась бы.
            events.unsubscribe(sub)
            logger.info("events_stream_closed user=%s subscribers=%s",
                        email, events.subscriber_count())

    return StreamingResponse(frames(), media_type="text/event-stream",
                             headers=STREAM_HEADERS)
