"""Воркер прогонов: длинные операции, снятые с очереди.

Запускается тем же образом, что и API, но другой командой:

    arq app.workers.jobs.WorkerSettings

**Почему прогон — отдельный процесс.** `reclassify --scope all` идёт до часа. Всё это
время он делил event loop с ручками интерфейса, умирал вместе с процессом API при
любой выкатке и не был виден ниоткуда, кроме этого же процесса. Строка в `runs`
чинила видимость, но не исполнение: пометить прогон прерванным — не то же самое, что
дать ему пережить рестарт API.

**Что переехало, а что нет.** Переехало место исполнения — и только оно. Сам прогон
зовётся тем же `jobs.execute`, что и в ветке без очереди: ветка без очереди остаётся
рабочим режимом стенда и тестов, и разойтись эти две дороги не имеют права — разница
вылезла бы там, где второй дороги нет, то есть на проде.

**Ретраев нет: `max_tries = 1`.** Это противоположность решению воркера приёма, и
причина в цене работы, а не в её надёжности. Разбор вебхука стоит миллисекунды, и
повтор после упавшего Postgres дешевле потерянного события. Прогон стоит час
видеокарты, на которой в это же время работает живой каскад, и «повторить с нуля» —
решение, которое принимает человек, глядя на экран, а не цикл повторов, пока никто не
смотрит. Сверх того, повтор переписал бы `started_at` и прогресс уже существующей
строки: оператор увидел бы, как полоса откатывается назад, без единого объяснения.

Что при этом фактически делает arq 0.28 (`.venv/Lib/site-packages/arq/worker.py`):

* работа снимается с очереди только по завершении (`finish_job`, `zrem` под
  `if finish`). Воркер, убитый посреди неё, ничего не снимает;
* на время исполнения ставится ключ `arq:in-progress:<id>` с TTL
  `job_timeout + 10` секунд (`worker.py:277`, `worker.py:465`), и пока он жив, работу
  не подберёт никто (`worker.py:455`);
* счётчик попыток `arq:retry:<id>` увеличивается **в начале** работы
  (`worker.py:482`), живёт сутки и смерть воркера переживает;
* поэтому при `max_tries = 1` повторно подобранная работа падает на проверке
  `job_try > max_tries` (`worker.py:550`) и снимается с очереди, **не дойдя до нашей
  функции**. Прогон с нуля не начинается — ровно то, что нужно;
* по SIGTERM (`docker stop`, выкатка) arq отменяет корутину и кладёт работу обратно в
  очередь немедленно (`worker.py:626`, `finish` остаётся `False`). Отменённую корутину
  мы ловим сами — см. `run_job`, — а следующая попытка снова упрётся в `max_tries`.

Обратная сторона честная и названная вслух: строку, чей воркер убили сигналом `KILL`,
не пометит никто до старта следующего воркера. Поэтому `startup` метит их сам — это и
есть единственное место, где такая пометка не враньё.

**`job_timeout = 4 часа.`** У воркера приёма он 300 секунд, здесь этого мало на
порядок. Наблюдаемый потолок — час на двенадцати тысячах сообщений; вчетверо больше —
запас на рост накопленного и на медленный день видеокарты. Бесконечным он быть не
может: зависший прогон держал бы единственный слот работы, а `wait_for`
(`worker.py:599`) — единственное, что о нём вообще способно сказать. Верхняя граница
тоже не произвольна: тот же таймаут задаёт TTL ключа «в работе», и держать его
сравнимым с сутками, за которые протухает сама работа, значило бы оставлять мёртвые
записи в очереди на весь день.

**`keep_result = 0`.** У приёма результат живёт сутки и работает ключом от повторной
доставки. Здесь повторной доставки нет — каждый запуск заводит новую строку, а от двух
одновременных прогонов защищает `active_run` в базе. Хранить же итог прогона в Redis
значило бы завести **второе место, где живёт правда о задаче**, рядом со строкой в
`runs`, у которой есть и статус, и результат, и лог. Два источника истины расходятся
всегда; этот не заводится вовсе (`worker.py:645`).
"""
from __future__ import annotations

import asyncio
import logging

from app.core.config import get_settings
from app.db.session import get_engine, get_session_maker
from app.services import alerts, embeddings, jobs, llm, queue

logger = logging.getLogger(__name__)

# Повторов нет. Единица — не «пока не сделали ретраи», а решение: см. докстроку модуля.
MAX_TRIES = 1

# Четыре часа на прогон. Обоснование — в докстроке модуля.
JOB_TIMEOUT = 4 * 60 * 60

# Одна работа за раз. `active_run` не пускает два прогона одного вида, но не мешает
# двум разным видам сойтись на одной видеокарте — а упираются в неё все, кто здесь
# исполняется. Ждать своей очереди честнее, чем делить карту пополам и вдвое
# растягивать оба прогона.
MAX_JOBS = 1


async def _alert(key: str, text: str) -> None:
    """Тревога отдельной сессией.

    Своей — потому что зовут её из веток, где сессия задачи уже закрыта или негодна.
    Писать тревогу в сломанную транзакцию значит потерять её вместе с той ошибкой, о
    которой она сообщает.
    """
    try:
        async with get_session_maker()() as db:
            await alerts.emit(db, key=key, text=text, severity="error")
            await db.commit()
    except Exception:  # noqa: BLE001 — тревога не вправе добить задачу
        logger.exception("jobs_alert_failed key=%s", key)


async def run_job(ctx: dict, run_id: int, kind: str, params: dict) -> dict:
    """Провести один прогон.

    Ошибки прогона наружу не выходят: `jobs.execute` сам пишет статус `failed`, лог и
    тревогу. Бросать их дальше было бы вредно вдвойне — arq записал бы работу в
    неудачные вторым местом, а при `max_tries = 1` это ничего не меняет.

    Ловится ровно одно исключение — `CancelledError`. Так выглядит остановка воркера
    сигналом: arq отменяет корутину работы и кладёт работу обратно в очередь. Строку
    в этот момент надо закрыть честно, иначе она останется «выполняется» до старта
    следующего воркера, а прогресс на экране замрёт без объяснения.
    """
    if kind not in jobs.RUNNERS:
        # Постановщик этот список уже проверял, значит воркер и API разъехались по
        # коду — обычно недокаченный образ у одного из контейнеров. Молча оставить
        # строку в «в очереди» нельзя: работы для неё в этой сборке нет вовсе.
        await jobs.finish(run_id, status="failed",
                          error=f"вид задачи «{kind}» неизвестен исполнителю",
                          note=f"вид задачи «{kind}» неизвестен исполнителю")
        await _alert("run_kind_unknown",
                     f"Воркер прогонов не знает вида «{kind}» (задача #{run_id}): "
                     f"похоже, образы API и воркера разошлись по коду")
        return {"run": run_id, "kind": kind, "rejected": "неизвестный вид"}

    try:
        await jobs.execute(run_id, kind, params)
    except asyncio.CancelledError:
        await jobs.finish(run_id, status="interrupted",
                          error="воркер прогонов остановлен во время выполнения",
                          note="воркер остановлен — прогон оборван")
        logger.warning("job_cancelled_by_shutdown run=%s kind=%s", run_id, kind)
        raise
    return {"run": run_id, "kind": kind}


async def startup(ctx: dict) -> None:
    """То же, что делает `lifespan` API, минус всё, что относится к ручкам.

    Короче, чем у воркера приёма, и это не упущение: прогон ходит в базу, в эмбеддинги
    и в модель, но не в Engage — `reclassify` тянет `drafting`, `targeting`,
    `embeddings` и `llm`, и ни один из них Telegram не трогает. Реестр инстансов
    Engage поэтому не поднимается: процесс, подключающий то, чем не пользуется, врёт
    о своих зависимостях.

    Пометка прерванных прогонов живёт здесь по той же причине, по которой ушла из
    API: с включённой очередью прогоны идут в этом процессе, и смерть переживают
    именно его строки. Сужение до «выполняется» — не мелочь: строка в «в очереди»
    смерти процесса не пережила, она лежит в Redis и ждёт, когда её возьмут, а взять
    её собирается тот же воркер секундой позже.
    """
    get_settings().validate_runtime()
    if not queue.enabled():
        # Воркер без очереди не «работает вхолостую» — он не работает вовсе, а
        # процесс, который поднялся и молчит, выглядит исправным ровно до первого
        # вопроса «почему прогон не начинается».
        raise RuntimeError(
            "RADAR_REDIS_URL не задан: воркеру прогонов неоткуда брать работу")

    stale = await jobs.mark_interrupted(statuses=("running",))
    if stale:
        logger.warning("jobs_interrupted_on_start count=%s", stale)
    logger.info("jobs_worker_started")


async def shutdown(ctx: dict) -> None:
    await embeddings.close()
    await llm.close()
    await queue.close()
    await get_engine().dispose()
    logger.info("jobs_worker_stopping")


class WorkerSettings:
    functions = [run_job]
    on_startup = startup
    on_shutdown = shutdown
    max_tries = MAX_TRIES
    job_timeout = JOB_TIMEOUT
    max_jobs = MAX_JOBS
    keep_result = 0

    # Считается при импорте, и отложить это некуда: arq читает `__dict__` класса
    # настроек и никаких функций не зовёт (`arq.worker.get_kwargs`). Поэтому импорт
    # обязан быть безобидным, а незаданный адрес ловится в `startup` — см. там.
    redis_settings = queue.redis_settings(fallback=True)
