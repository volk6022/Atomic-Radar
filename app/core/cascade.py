"""Каскад L0→L1: дешёвый отсев до того, как за сообщение возьмётся модель.

Порядок ступеней — не украшение, а способ уложиться в железо. Одна активная группа
даёт около 9000 сообщений в сутки; прогонять их все через LLM невозможно ни по
времени, ни по деньгам, поэтому до модели доходят единицы процентов.

* **L0 — структура.** Автопересылка поста канала, бот, пустой или слишком короткий
  текст. Здесь нет ни одного слова про предметную область: это отсев того, что вообще
  не является репликой человека.
* **L1 — слова.** Совпадение с якорями боли. Грубо, но именно этот шаг убирает 95 %
  остатка и стоит микросекунды.
* **L2 (эмбеддинги) и L3 (LLM)** появятся отдельно. Пока их нет, `cascade_level`
  честно останавливается на 1, а не притворяется, что сообщение прошло всю цепочку.

Модуль намеренно без БД и без FastAPI: одни и те же функции зовут ингест и тесты,
иначе правило, живущее только в тестах, в проде не соблюдается.
"""
from __future__ import annotations

import re
from datetime import datetime, timedelta, timezone

MIN_TEXT_LENGTH = 15

# Отдельного порога на скор здесь нет, и это осознанно.
#
# Сначала он был: «лид, если сумма ≥ 35». На живых данных выяснилось две вещи.
# Во-первых, порог по полной сумме почти обнулил сухой прогон: у любого сообщения из
# истории свежесть равна нулю, то есть история штрафовалась просто за то, что она
# история. Во-вторых, после того как L1 стал требовать И тему, И признак проблемы,
# минимально возможная содержательная оценка сравнялась с порогом — то есть порог
# перестал что-либо отсекать и остался бы настройкой, которая ничего не настраивает.
#
# Решение о том, лид это или нет, принимает условие на L1. Скор остаётся оценкой
# качества и определяет очерёдность в очереди, а не факт попадания в неё.

# Якоря боли под профиль заказчика: хостинг, VPS, VPN, self-hosted инфраструктура.
# Ключ — короткое имя боли, оно же попадёт в карточку лида.
PAIN_ANCHORS: dict[str, tuple[str, ...]] = {
    "хостинг тормозит/дорог": (
        "хостинг", "хостинге", "хостинга", "хостингом", "vps", "впс", "вдс", "vds",
        "сервер тормозит", "дорогой сервер", "переехать с",
    ),
    "VPN не работает": (
        "vpn", "впн", "прокси не работает", "обход блокировок", "outline", "vless",
        "wireguard", "amnezia",
    ),
    "не может настроить сам": (
        "3x-ui", "3x ui", "marzban", "remnawave", "не могу настроить", "не получается настроить",
        "запутался", "как поднять", "как настроить", "помогите настроить",
    ),
    "нужен админ/подрядчик": (
        "ищу админа", "нужен админ", "нужен devops", "ищу devops", "кто может настроить",
        "посоветуйте специалиста", "нужен человек",
    ),
}

# Слова, из-за которых сообщение не стоит трогать, даже если якорь совпал.
DISQUALIFIERS: dict[str, tuple[str, ...]] = {
    "сам продаёт услугу": ("предлагаю услуги", "оказываю услуги", "мои услуги", "прайс",
                           "обращайтесь", "пишите в лс", "недорого"),
    "реклама/спам": ("розыгрыш", "промокод", "скидка", "распродажа", "курс по"),
    "вакансия": ("вакансия", "резюме", "ищем в команду", "зарплата"),
}

# Признаки, что у человека проблема, а не просто разговор на тему. Первый прогон по
# живым чатам показал, почему без них нельзя: одного слова «впн» хватало, чтобы
# лидом стали «Его через впн использовать ??» и «А чем потеряпамятивпн не устроил?».
# Тема без проблемы — это болтовня, а не боль.
PROBLEM_MARKERS = ("не работает", "не могу", "не получается", "не пойму", "не понимаю",
                   "перестал", "перестало", "отвалил", "отваливается", "падает",
                   "лежит", "тормозит", "медленно", "виснет", "зависает", "ошибка",
                   "проблема", "сломал", "не запускается", "не поднимается",
                   "помогите", "запутал", "не стартует", "потерял")

INTENT_MARKERS = ("посовет", "подскаж", "помог", "ищу", "нужен", "нужна", "нужно",
                  "как быть", "что делать", "кто знает", "кто-нибудь", "кто может",
                  "как настроить", "как поднять")
URGENCY_MARKERS = ("срочно", "горит", "задолбал", "заебал", "достало", "задрало",
                   "не работает", "постоянно", "который день")
DECISION_MAKER_MARKERS = ("у нас в компании", "наша команда", "у нас на проекте",
                          "мой проект", "мои клиенты", "у меня бизнес", "наш сервер",
                          "у нас сервер", "клиенты жалуются")

# Матчится ссылка целиком, а не только её начало: вырезать один «https://» и мерить
# остаток бессмысленно — длинный путь URL сам по себе перевалит любой порог.
_URL = re.compile(r"(?:https?://|t\.me/|www\.)\S*")
_COMMAND = re.compile(r"^/\w+")


def _norm(text: str | None) -> str:
    return (text or "").lower().replace("ё", "е")


# ── L0: структура ─────────────────────────────────────────────────────────────

def level0(*, text: str | None, is_automatic_forward: bool, author_is_bot: bool,
           author_peer_id: int | None) -> tuple[bool, str]:
    """Это вообще реплика живого человека? Возвращает (прошло, причина)."""
    if is_automatic_forward:
        return False, "автопересылка поста канала — это не реплика человека"
    if author_is_bot:
        return False, "автор — бот"
    if author_peer_id is None:
        return False, "у сообщения нет автора (анонимный админ или пост канала)"

    body = (text or "").strip()
    if not body:
        return False, "пустой текст (медиа без подписи)"
    if _COMMAND.match(body):
        return False, "команда боту"
    if len(body) < MIN_TEXT_LENGTH:
        return False, f"длина {len(body)} < {MIN_TEXT_LENGTH}"
    # Голая ссылка без слов — почти всегда репост или реклама.
    if _URL.search(body) and len(_URL.sub("", body).strip()) < MIN_TEXT_LENGTH:
        return False, "только ссылка без текста"

    return True, f"не пост канала, длина {len(body)}, автор не бот"


# ── L1: слова ─────────────────────────────────────────────────────────────────

def level1(text: str | None) -> tuple[bool, str, str | None, list[str]]:
    """Тема плюс признак проблемы.

    Возвращает (прошло, причина, имя боли, сработавшие якоря). Одного попадания в тему
    мало: нужен ещё либо признак поломки, либо явная просьба о помощи. Проверено на
    живых чатах — без этого условия в лиды попадала половина обычной болтовни.
    """
    body = _norm(text)
    for pain, anchors in PAIN_ANCHORS.items():
        hits = [a for a in anchors if a in body]
        if not hits:
            continue

        problems = [m for m in PROBLEM_MARKERS if m in body]
        intents = [m for m in INTENT_MARKERS if m in body]
        if not problems and not intents:
            return (False,
                    f"тема совпала ({', '.join('«' + h + '»' for h in hits[:2])}), "
                    f"но нет ни признака проблемы, ни просьбы о помощи",
                    None, [])

        why = "совпало " + ", ".join("«" + h + "»" for h in hits[:3])
        if problems:
            why += " + проблема «" + problems[0] + "»"
        elif intents:
            why += " + просьба «" + intents[0] + "»"
        # Наружу отдаём только тематические попадания: слагаемые «интент» и
        # «срочность» считаются отдельно, и складывать их в один список значило бы
        # засчитать одно и то же дважды.
        return True, why, pain, hits

    return False, "ни одного якоря боли", None, []


def disqualifiers(text: str | None) -> list[str]:
    """Признаки, из-за которых писать не стоит, даже если боль совпала.

    Не отсев, а пометка: решение остаётся за человеком, но он должен увидеть, что
    автор сам продаёт такие же услуги, — писать ему предложение бессмысленно.
    """
    body = _norm(text)
    return [name for name, words in DISQUALIFIERS.items() if any(w in body for w in words)]


# ── скоринг ───────────────────────────────────────────────────────────────────

def _hits(body: str, markers: tuple[str, ...]) -> int:
    return sum(1 for m in markers if m in body)


def score(*, text: str | None, anchors: list[str], tg_date: datetime,
          now: datetime, has_username: bool) -> tuple[int, list[dict]]:
    """Оценка 0-100 с разбором по слагаемым.

    Слагаемые те же, что нарисованы в интерфейсе, и считаются здесь, а не на клиенте:
    экран показывает разбор именно для того, чтобы оценке можно было не верить на слово.

    Пока это арифметика по словам, без модели. Числа получаются грубые — и это
    честнее, чем выдать эвристику за вывод LLM.
    """
    body = _norm(text)

    pain = min(32, 12 + 10 * len(anchors))
    # Прямая просьба о помощи («подскажите») — это и есть главный сигнал, ради
    # которого всё затевалось, поэтому одно такое слово весит заметно.
    intent = min(24, 8 * _hits(body, INTENT_MARKERS) + 8 * _hits(body, PROBLEM_MARKERS)
                 + 7 * _hits(body, URGENCY_MARKERS))
    lpr = min(15, 8 * _hits(body, DECISION_MAKER_MARKERS))

    age = now - tg_date
    if age < timedelta(hours=6):
        fresh = 10
    elif age < timedelta(days=1):
        fresh = 7
    elif age < timedelta(days=7):
        fresh = 3
    else:
        fresh = 0

    # Без username в личку не написать — Engage резолвит пира по нему.
    reach = 6 if has_username else 0

    breakdown = [
        {"label": "совпадение с болью", "value": pain},
        {"label": "срочность/интент", "value": intent},
        {"label": "признаки ЛПР", "value": lpr},
        {"label": "свежесть", "value": fresh},
        {"label": "достижимость в ЛС", "value": reach},
    ]
    return sum(b["value"] for b in breakdown), breakdown


# ── всё вместе ────────────────────────────────────────────────────────────────

def classify(*, text: str | None, is_automatic_forward: bool, author_is_bot: bool,
             author_peer_id: int | None, author_username: str | None,
             tg_date: datetime, now: datetime | None = None) -> dict:
    """Прогнать сообщение по каскаду и вернуть всё, что о нём стало известно.

    Ответ одной формы независимо от того, на какой ступени сообщение остановилось:
    экран потока показывает по каждой ступени либо вердикт, либо «не запускалась», и
    разница между «не прошло» и «не дошло» должна быть видна в данных, а не додумываться.
    """
    now = now or datetime.now(timezone.utc)
    if tg_date.tzinfo is None:
        tg_date = tg_date.replace(tzinfo=timezone.utc)

    ok0, why0 = level0(text=text, is_automatic_forward=is_automatic_forward,
                       author_is_bot=author_is_bot, author_peer_id=author_peer_id)
    detail = {"l0": why0, "l1": None, "l2": None, "l3": None}
    if not ok0:
        detail["l1"] = "не запускался: отсеяно на L0"
        detail["l2"] = "не запускался: отсеяно на L0"
        detail["l3"] = "не запускался: отсеяно на L0"
        return {"level": 0, "passed": False, "detail": detail, "pain": None,
                "score": 0, "breakdown": [], "disqualifiers": []}

    ok1, why1, pain, anchors = level1(text)
    detail["l1"] = why1
    if not ok1:
        detail["l2"] = "не запускался: отсеяно на L1"
        detail["l3"] = "не запускался: отсеяно на L1"
        return {"level": 1, "passed": False, "detail": detail, "pain": None,
                "score": 0, "breakdown": [], "disqualifiers": []}

    total, breakdown = score(text=text, anchors=anchors, tg_date=tg_date, now=now,
                             has_username=bool(author_username))

    # L2/L3 ещё не построены. Пишем это прямым текстом: пустая строка на экране
    # читалась бы как «ступень пройдена».
    detail["l2"] = "не запускался: эмбеддинги ещё не подключены"
    detail["l3"] = "не запускался: LLM ещё не подключена"

    return {"level": 1, "passed": True, "detail": detail, "pain": pain,
            "score": total, "breakdown": breakdown,
            "disqualifiers": disqualifiers(text)}
