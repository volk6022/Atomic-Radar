def all_prototypes() -> list[tuple[str, str, str]]:
    """Плоский список `(kind, label, text)`, kind = "pos" | "neg".

    Порядок фиксирован (dict в Python сохраняет порядок вставки), поэтому индексы
    эмбеддингов совпадают с этим списком и их не нужно сопоставлять по тексту.
    """
    out: list[tuple[str, str, str]] = []
    for label, texts in POSITIVE.items():
        out.extend(("pos", label, t) for t in texts)
    for label, texts in NEGATIVE.items():
        out.extend(("neg", label, t) for t in texts)
    return out
