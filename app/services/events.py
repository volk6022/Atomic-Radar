"""Поток изменений для интерфейса: один опрос базы на процесс, много подписчиков.

**Событие рождается из опроса базы, а не из места, где что-то изменилось.** Очевидный
путь — публиковать прямо там, где принято решение, — разобран и отвергнут, и каждой из
причин по отдельности хватило бы:

* решения по целям и черновикам разложены по двенадцати ручкам с двенадцатью
  собственными `db.commit()`: публикацию пришлось бы дописать в каждую — и в каждую
  будущую, а забытая строчка выглядит не как ошибка, а как «экран иногда не
  обновляется»;
* `alerts.emit` намеренно не коммитит — тревога уезжает вместе с транзакцией
  вызывающего. Публикация изнутри `emit` анонсировала бы то, что строкой ниже
  откатится;
* черновики заводятся внутри `GET`-ручек `wf_queues.py`, где точки «здесь изменилось»
  просто нет;
* переклассификация меняет всё в одной длинной транзакции с единственным коммитом в
  конце — до него публиковать нечего, после него публиковать поздно;
* с включённой очередью приём идёт в другом процессе, и внутрипроцессная шина его не
  увидела бы вовсе.

Опрос базы не имеет ни одной из этих бед: он видит закоммиченное, чей бы процесс его
ни записал. Отсюда три следствия, ради которых решение и выбрано: Redis не нужен
(воркер пишет в ту же базу, из которой читает API), стенд и прод устроены одинаково,
новых зависимостей нет.

Принцип не новый — он уже записан в докстроке `app/services/jobs.py`: источник истины
это строка в базе, а не переменная в памяти. Здесь он доведён до конца: в памяти не
хранится ничего, кроме прошлого снимка, нужного ровно затем, чтобы отличить
изменившееся от неизменившегося.

**Опрос живёт ровно столько, сколько есть кому слушать.** В `lifespan` он не заводится
намеренно: тестам и стенду не нужен вечный фоновой цикл, который никто не читает, а
«появился первый подписчик / ушёл последний» — единственное честное условие его
существования.

**Потеря промежуточного состояния здесь безопасна, и это не совпадение, а свойство
контракта.** Каждое событие несёт текущее значение целиком, а не приращение к
предыдущему: `alerts` — сколько непрочитанных сейчас, `runs` — какие прогоны идут
сейчас. Поэтому отставшему подписчику можно молча выбросить накопившуюся очередь и
выдать состояние заново — он окажется ровно там же, где все остальные. Будь события
приращениями, такой выброс означал бы навсегда разошедшуюся картинку, и очередь
пришлось бы либо растить без предела, либо рвать соединение.
"""
from __future__ import annotations

import asyncio
import contextlib
import logging

from sqlalchemy import func, select

from app.core.access import Section, can
from app.core.config import get_settings
from app.db.models import Alert, Conversation, Draft, Run
from app.db.session import get_session_maker
from app.services import jobs

logger = logging.getLogger("radar.events")

# Какой раздел матрицы нужен, чтобы получать событие. Одного `requires(...)` на всю
# ручку не хватает: тревоги открыты даже гостю (раздел `dashboard` доступен всем
# ролям), а прогоны — только штату. Ручка с единственной проверкой либо не пустила бы
# гостя вовсе, либо отдала бы ему прогоны.
#
# Раздел берётся не «по смыслу», а тот же, которым закрыта соответствующая ручка
# опроса: `alerts` и `counters` — `Section.DASHBOARD` (`app/api/v1/alerts.py`,
# `app/api/v1/screens.py:counters`), `runs` — `Section.RUNS` (`app/api/v1/runs.py`).
# Придумать потоку правило строже, чем у ручки, значило бы развести их между собой:
# одно и то же число приезжало бы гостю опросом и не приезжало потоком.
EVENT_SECTIONS: dict[str, Section] = {
    "alerts": Section.DASHBOARD,
    "counters": Section.DASHBOARD,
    "runs": Section.RUNS,
}

# Порядок, в котором рассылается полный снимок. Зафиксирован, чтобы у только что
# открытого экрана порядок первых кадров не зависел от порядка обхода словаря.
EVENT_ORDER: tuple[str, ...] = ("alerts", "counters", "runs")

# Сколько кадров держим за отставшим подписчиком, прежде чем выдать ему состояние
# заново. Опрос кладёт не больше трёх кадров за такт, так что предел — это примерно
# два десятка тактов молчания читателя; живой браузер столько не молчит, а мёртвого
# всё равно снимет разрыв соединения.
QUEUE_LIMIT = 64


class Subscriber:
    """Один открытый поток.

    Права считаются один раз, здесь, и дальше не перепроверяются — см. докстроку
    ручки `app/api/v1/events.py`: это осознанное ограничение, а не забывчивость.
    """

    def __init__(self, role: str) -> None:
        self.role = role
        self.queue: asyncio.Queue[tuple[str, dict]] = asyncio.Queue(QUEUE_LIMIT)
        self.allowed = frozenset(
            name for name, section in EVENT_SECTIONS.items() if can(role, section))
        # Сколько раз подписчик отставал настолько, что ему выдавали состояние
        # заново. Ноль на живом интерфейсе; растущее число — повод смотреть на клиента.
        self.resyncs = 0

    def wants(self, name: str) -> bool:
        """Положено ли подписчику это событие. Служебные (`hello`, `error`) — всем:
        они про сам поток, а не про данные, и прятать их не от чего."""
        return name not in EVENT_SECTIONS or name in self.allowed

    def push(self, name: str, data: dict) -> bool:
        """Положить кадр. `False` — очередь переполнена, подписчик отстал."""
        if not self.wants(name):
            return True
        try:
            self.queue.put_nowait((name, data))
        except asyncio.QueueFull:
            return False
        return True

    def resync(self, frames: list[tuple[str, dict]]) -> None:
        """Догнать отставшего текущим состоянием, а не хвостом истории.

        Выбрасываем накопившееся целиком и кладём снимок заново. Это законно ровно
        потому, что каждое событие несёт значение целиком (см. докстроку модуля):
        выброшенные кадры не содержали ничего, чего нет в снимке. Альтернативы хуже:
        «выбросить самый старый» оставляет подписчика со стухшим значением того вида,
        который больше не менялся, а «рвать соединение» наказывает за медленную сеть
        потерей потока.
        """
        while not self.queue.empty():
            self.queue.get_nowait()
        self.resyncs += 1
        for name, data in frames:
            self.push(name, data)


# Всё состояние рассыльщика живёт в одном event loop, и трогают его только синхронные
# функции без единого `await` внутри. Поэтому блокировок здесь нет и не нужно: между
# «проверил» и «записал» управление некому перехватить. На это же опирается уговор
# между `subscribe`, `unsubscribe` и `_poll_loop` — см. `unsubscribe`.
_subscribers: set[Subscriber] = set()
_poller: asyncio.Task | None = None
_stop: asyncio.Event | None = None
_state: dict[str, dict] | None = None
_failure: str | None = None


def subscribe(role: str) -> Subscriber:
    """Завести подписчика и, если он первый, поднять опрос.

    Полный снимок кладётся сразу, а не ждёт первого изменения: только что открытый
    экран иначе слеп до тех пор, пока в системе что-нибудь не произойдёт, а произойти
    может и через час. Если опрос ещё ни разу не отработал (подписчик первый), снимка
    нет — его разошлёт первый же такт, который делается без задержки.

    Опрос, которому уже сказали гаснуть, но который ещё не догорел, здесь просто
    передумывает гаснуть. Это дешевле и честнее, чем поднимать второй рядом с
    доживающим первым: между «ушёл последний» и «пришёл новый» на перезагрузке
    страницы проходят миллисекунды.
    """
    global _poller, _stop

    sub = Subscriber(role)
    _subscribers.add(sub)
    if _state is not None:
        for name, data in _frames(_state):
            sub.push(name, data)
    if _failure is not None:
        # Пришедшему во время аварии честнее сразу сказать, что показанное может быть
        # несвежим, чем молча отдать последний удачный снимок.
        sub.push("error", {"text": _failure})

    if _poller is None:
        _stop = asyncio.Event()
        _poller = asyncio.create_task(_poll_loop(_stop), name="radar-events-poll")
    elif _stop is not None:
        _stop.clear()
    return sub


def unsubscribe(sub: Subscriber) -> None:
    """Снять подписку и, если она была последней, попросить опрос погаснуть.

    Функция намеренно синхронная и без единого `await`. Зовут её из `finally`
    генератора ответа, а тот выполняется в том числе под отменой корутины — закрытая
    вкладка, обрыв сети, уход со страницы. В отменённой задаче любое ожидание
    немедленно получает `CancelledError`, и уборка, написанная через `await`, молча не
    доделалась бы: подписчик остался бы в наборе, а опрос — навсегда живым.

    **Просьба, а не `cancel()`, и это не вежливость.** Отмена приходит в произвольную
    точку, чаще всего — в середину запроса к базе: сессия в этот момент внутри
    `async with`, её закрытие само сделано через `await`, и в отменённой задаче оно не
    доживает до конца. Соединение остаётся в пуле с **открытой транзакцией**, держит
    блокировки и никем не возвращается. Найдено это ровно так, как такое и находится:
    следующая же попытка накатить схему на тестовой базе встала намертво в ожидании
    блокировки, оставленной опросом, погашенным на предыдущем тесте. Поэтому опрос
    гасится на границе такта, где ничего не открыто.

    Уговор с `_poll_loop` держится на том, что этот модуль живёт в одном event loop и
    трогают его только синхронные функции: пока цикл не дошёл до `await`, никакая
    `subscribe` не может увидеть его в промежуточном состоянии.
    """
    _subscribers.discard(sub)
    if _subscribers or _stop is None:
        return
    _stop.set()


def subscriber_count() -> int:
    """Сколько потоков открыто сейчас. Число уходит в лог при каждом закрытии: без
    него утечка подписок видна только по тому, что опрос не гаснет."""
    return len(_subscribers)


def poller_alive() -> bool:
    """Идёт ли сейчас опрос. Нужно ровно затем, чтобы это можно было проверить
    тестом: «гаснет, когда ушёл последний» — свойство, которое легко потерять правкой."""
    return _poller is not None and not _poller.done()


def _frames(state: dict[str, dict] | None) -> list[tuple[str, dict]]:
    if state is None:
        return []
    return [(name, state[name]) for name in EVENT_ORDER]


def _broadcast(frames: list[tuple[str, dict]]) -> None:
    """Разослать кадры подписчикам. Синхронно и без ожиданий: рассылка не должна
    зависеть от того, успевает ли читать самый медленный из них."""
    if not frames:
        return
    for sub in list(_subscribers):
        lagging = False
        for name, data in frames:
            if not sub.push(name, data):
                lagging = True
        if lagging:
            logger.warning("events_subscriber_lagging role=%s resyncs=%s",
                           sub.role, sub.resyncs + 1)
            catch_up = _frames(_state)
            if _failure is not None:
                catch_up.append(("error", {"text": _failure}))
            sub.resync(catch_up)


async def _snapshot() -> dict[str, dict]:
    """Компактный снимок состояния — короткой сессией, по образцу `jobs._touch`.

    Своя сессия на каждый снимок, а не одна на весь цикл: соединение, взятое из пула
    на часы, — это соединение, которого не хватит ручкам. Ровно та же причина, по
    которой сессию не держит и сама ручка потока.

    Считается здесь только то, что действительно отдаётся, и настолько дёшево,
    насколько выходит. `counters` — это те же два числа, что возвращает
    `app/api/v1/screens.py:counters`; звать оттуда `_counts` нельзя (сервис не ходит в
    ручки, да и незачем: опрос раз в пару секунд тянул бы за собой всю воронку
    дашборда). Расплата — два места, которые обязаны совпадать: правишь ручку —
    правь и здесь, иначе бейдж по опросу и бейдж по потоку разойдутся.
    """
    async with get_session_maker()() as db:
        unread = (await db.execute(
            select(func.count(Alert.id)).where(Alert.read_at.is_(None)))).scalar_one()
        drafts = (await db.execute(
            select(func.count(Draft.id)).where(Draft.state == "pending"))).scalar_one()
        conversations = (await db.execute(
            select(func.count(Conversation.id))
            .where(Conversation.state == "awaiting_reply"))).scalar_one()
        # Порядок задан явно: без него две одинаковые по смыслу выборки могут прийти
        # в разном порядке строк, и сравнение с прошлым снимком объявит изменением то,
        # что не менялось.
        runs = (await db.execute(
            select(Run.id, Run.kind, Run.status, Run.progress)
            .where(Run.status.in_(jobs.ACTIVE)).order_by(Run.id))).all()

    return {
        "alerts": {"unread": unread},
        "counters": {"drafts": drafts, "conversations": conversations},
        "runs": {"rows": [{"id": r.id, "kind": r.kind, "status": r.status,
                           "progress": float(r.progress or 0)} for r in runs]},
    }


async def _poll_loop(stop: asyncio.Event) -> None:
    """Читать снимок, сравнивать с прошлым, рассылать только изменившееся.

    Первый такт делается без задержки — иначе первый же подписчик ждал бы полный
    период до того, как увидит хоть что-нибудь.

    Ожидание между тактами — не `sleep`, а ожидание просьбы погаснуть с таймаутом:
    так цикл уходит сразу, как только закрылась последняя вкладка, но всегда на
    границе такта, где не открыто ни сессии, ни транзакции (см. `unsubscribe`).

    **Падение опроса не молчит.** База может быть недоступна, и притвориться, что
    ничего не изменилось, здесь худший из возможных ответов: экран замирает на старых
    числах и выглядит исправным. Поэтому авария уезжает подписчику отдельным событием
    `error`, а цикл продолжает работать — база возвращается сама, и рвать из-за неё
    все открытые потоки незачем. Событие шлётся на переходах, а не каждый такт: за
    минуту недоступности иначе набежало бы тридцать одинаковых кадров.
    """
    global _poller, _state, _stop, _failure

    interval = get_settings().EVENTS_POLL_INTERVAL
    try:
        while not stop.is_set():
            outgoing: list[tuple[str, dict]] = []
            try:
                snapshot = await _snapshot()
            except asyncio.CancelledError:
                raise
            except Exception as e:  # noqa: BLE001 — важен не вид ошибки базы, а факт
                text = f"{type(e).__name__}: {e}"
                if _failure != text:
                    _failure = text
                    logger.error("events_poll_failed error=%s", text)
                    outgoing.append(("error", {"text": text}))
            else:
                if _failure is not None:
                    _failure = None
                    logger.info("events_poll_recovered")
                    # `text: null` — «поток снова здоров». Отдельное имя события на
                    # выздоровление плодило бы клиенту второй обработчик ради бита.
                    outgoing.append(("error", {"text": None}))
                previous, _state = _state, snapshot
                outgoing += [(name, snapshot[name]) for name in EVENT_ORDER
                             if previous is None or previous[name] != snapshot[name]]

            _broadcast(outgoing)
            with contextlib.suppress(TimeoutError):
                await asyncio.wait_for(stop.wait(), interval)
    finally:
        # Убирает за собой сам цикл, а не тот, кто его погасил: сюда мы попадаем и по
        # просьбе, и по отмене задачи при остановке процесса, и уборка обязана
        # случиться в обоих случаях. Снимок и авария — состояние конкретного опроса;
        # оставить их значило бы выдать следующему пришедшему картину неизвестной
        # давности. Проверка `_stop is stop` — на случай, если нас уже сменили.
        if _stop is stop:
            _poller = _stop = None
            _state = _failure = None
