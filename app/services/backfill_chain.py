"""Заказ страниц истории — общее звено цепочки бэкфилла.

Функция жила приватной в ручке приёма (`app/api/v1/ingest.py`), но у неё
появился второй заказчик — исполнитель очереди дочитывания (`backfill_drain`).
Импорт сервиса из слоя ручек был бы инверсией слоёв, поэтому само звено
переехало сюда, а ручка и исполнитель зовут его из одного места: разойтись
«как заказывается страница» в двух модулях значило бы получить две цепочки с
разным адресом возврата и разным окном глубины.

Цепочку страниц двигает не наш процесс: Радар просит у Engage одну страницу,
Engage возвращает её вебхуком, и приёмная ручка просит следующую. Поэтому
здесь только заказ — ни ожидания, ни разбора.
"""
from __future__ import annotations

from app.services import engage

# Сколько сообщений просить за один вызов. Потолок Engage — 1000, но каждая страница
# приезжает одним вебхуком, и на тысяче постов это уже мегабайт JSON в одном запросе.
# 500 — компромисс: страниц вдвое больше, зато ни один ответ не становится проблемой
# сам по себе. Дневной бюджет чтений (2000 вызовов на аккаунт) при этом не жмёт.
PAGE_LIMIT = 500


async def request_page(*, peer_id: int, username: str | None,
                       account_id: int, limit: int, target: int,
                       max_id: int, cursor: int, run_id: int = 0,
                       min_date: str | None = None,
                       item_id: int = 0, read0: int = 0) -> None:
    """Заказать одну страницу истории. `cursor` едет обратно для защиты от зацикливания.

    `run_id` едет туда же: цепочку двигает Engage, а не наш процесс, и связать
    приехавшую страницу с задачей в `runs` можно только через адрес вебхука.

    `min_date` — граница окна глубины из элемента очереди, строкой ISO. Она
    кладётся в payload, а не фильтруется у нас: «не глубже месяца» — параметр
    самого `get_chat_history`, и постфильтр означал бы, что страницы за
    пределами окна всё равно прочитаны и списаны с дневного бюджета.

    Та же граница едет и в адрес возврата — иначе она действует ровно на одну
    страницу. Цепочку двигает приём (`_continue_backfill`), а он знает о цепочке
    только то, что написано в адресе: 05.09 окно лежало в одном payload, приём
    читал его из пустого места, и заказ «не глубже месяца» дочитал канал до
    ноября 2020 года — 2032 сообщения вместо трёх десятков, все через каскад.
    Окно — свойство цепочки, а не первой страницы.

    `item_id` и `read0` — принадлежность элементу очереди дочитывания и счётчик
    сообщений на момент старта цепочки. Без первого приёмная ручка не знает,
    какой элемент закрывать на конце цепочки; без второго `read_total`
    считался бы полным счётчиком канала и приписывал бы новому элементу всё,
    что прочитано раньше.

    Названия группы в адресе нет намеренно, и это не экономия. `tasks.webhook_url` у
    Engage — `varchar(500)`, а кириллическое название в percent-encoding раздувается
    вшестеро: у «ВЭД чат (таможенное оформление, сертификация, грузоперевозки, экспорт,
    импорт)» одно только название заняло больше четырёхсот символов, адрес не влез, и
    Engage ответил `500` на вставку задачи. Цепочка вставала на первой же странице —
    29.08 так потерялся весь бэкфилл @CentrVED. Название и не нужно: строка канала уже
    заведена шагом `chat_info`, а `get_or_create_channel` при пустом названии берёт
    существующее. В адрес возврата кладём только то, без чего страницу не привязать.
    """
    payload: dict = {"username": username or str(peer_id), "limit": limit}
    if max_id:
        payload["max_id"] = max_id
    if min_date:
        payload["min_date"] = min_date
    back: dict = {"kind": "history", "peer_id": peer_id,
                  "username": username or "", "account_id": account_id,
                  "limit": limit, "target": target, "prev_cursor": cursor,
                  "run_id": run_id, "item_id": item_id, "read0": read0}
    if min_date:
        back["min_date"] = min_date
    await engage.action(
        account_id=account_id, action="get_chat_history", payload=payload,
        webhook_url=engage.webhook_url(**back))
